#!/usr/bin/env bash
/usr/bin/qemu-system-x86_64 \
    -name fedora-44-plasma,process=fedora-44-plasma,debug-threads=on \
    -machine q35,smm=off,vmport=off,accel=kvm \
    -global kvm-pit.lost_tick_policy=discard \
    -cpu host \
    -smp cores=2,threads=2,sockets=1 \
    -m 8G \
    -device virtio-balloon \
    -pidfile fedora-44-plasma/fedora-44-plasma.pid \
    -rtc base=utc,clock=host \
    -vga none \
    -device virtio-gpu,xres=1280,yres=800 \
    -display none \
    -spice disable-ticketing=on,port=5930,addr=127.0.0.1 \
    -device virtio-serial-pci \
    -chardev socket,id=agent0,path=fedora-44-plasma/fedora-44-plasma-agent.sock,server=on,wait=off \
    -device virtserialport,chardev=agent0,name=org.qemu.guest_agent.0 \
    -chardev spicevmc,id=vdagent0,name=vdagent \
    -device virtserialport,chardev=vdagent0,name=com.redhat.spice.0 \
    -chardev spiceport,id=webdav0,name=org.spice-space.webdav.0 \
    -device virtserialport,chardev=webdav0,name=org.spice-space.webdav.0 \
    -device virtio-rng-pci,rng=rng0 \
    -object rng-random,id=rng0,filename=/dev/urandom \
    -device qemu-xhci,id=spicepass \
    -chardev spicevmc,id=usbredirchardev1,name=usbredir \
    -device usb-redir,chardev=usbredirchardev1,id=usbredirdev1 \
    -chardev spicevmc,id=usbredirchardev2,name=usbredir \
    -device usb-redir,chardev=usbredirchardev2,id=usbredirdev2 \
    -chardev spicevmc,id=usbredirchardev3,name=usbredir \
    -device usb-redir,chardev=usbredirchardev3,id=usbredirdev3 \
    -device pci-ohci,id=smartpass \
    -device usb-ccid \
    -chardev spicevmc,id=ccid,name=smartcard \
    -device ccid-card-passthru,chardev=ccid \
    -device usb-ehci,id=input \
    -device usb-kbd,bus=input.0 \
    -k en-us \
    -device usb-tablet,bus=input.0 \
    -audiodev spice,id=audio0 \
    -device intel-hda \
    -device hda-micro,audiodev=audio0 \
    -device virtio-net-pci,netdev=nic \
    -netdev user,hostname=fedora-44-plasma,hostfwd=tcp::22220-:22,smb=/home/restoredelight/Public,id=nic \
    -global driver=cfi.pflash01,property=secure,value=on \
    -drive if=pflash,format=qcow2,unit=0,file=/usr/share/edk2/ovmf/OVMF_CODE_4M.qcow2,readonly=on \
    -drive if=pflash,format=qcow2,unit=1,file=fedora-44-plasma/OVMF_VARS.qcow2 \
    -device virtio-blk-pci,drive=SystemDisk \
    -drive id=SystemDisk,if=none,format=qcow2,file=fedora-44-plasma/disk.qcow2,discard=unmap,detect-zeroes=unmap,cache=writeback,aio=threads \
    -fsdev local,id=fsdev0,path=/home/restoredelight/Public,security_model=mapped-xattr \
    -device virtio-9p-pci,fsdev=fsdev0,mount_tag=Public-restoredelight \
    -monitor unix:fedora-44-plasma/fedora-44-plasma-monitor.socket,server,nowait \
    -serial unix:fedora-44-plasma/fedora-44-plasma-serial.socket,server,nowait \
    -qmp unix:fedora-44-plasma/fedora-44-plasma-qmp.sock,server,nowait \
    -m 3G 2>/dev/null
